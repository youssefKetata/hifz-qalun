// Build the personal Shami reference from the audited Kotteb page metadata.
// Usage: node scripts/build-shami-reference.mjs path/to/page-records.json
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { format } from 'prettier';
const pages = JSON.parse(await readFile(process.argv[2], 'utf8')).sort(
  (a, b) => a.pageInfo.pageNumber - b.pageInfo.pageNumber,
);
const existing = JSON.parse(await readFile(new URL('../surahs-qalun.json', import.meta.url)));
const verses = [],
  bands = [],
  pageEnds = [],
  counts = Array(114).fill(0);
assert.equal(pages.length, 604);
for (const [index, image] of pages.entries()) {
  const p = image.pageInfo;
  assert.equal(p.pageNumber, index + 1);
  const boxes = p.ayahInfoList.flatMap((v) => v.boxesToHighlight);
  const top = Math.min(...boxes.map((b) => b.startCoordinates[1]));
  const bottom = Math.max(...boxes.map((b) => b.endCoordinates[1]));
  assert.ok(bottom > top);
  for (const v of p.ayahInfoList) {
    const [s, a] = v.key.split('-').map(Number);
    assert.equal(v.ayahId, verses.length + 1);
    assert.equal(a, ++counts[s - 1]);
    assert.ok(v.text.trim());
    verses.push(v.text);
    bands.push([
      Math.round(
        ((Math.min(...v.boxesToHighlight.map((b) => b.startCoordinates[1])) - top) / (bottom - top)) * 10000,
      ),
      Math.round(
        ((Math.max(...v.boxesToHighlight.map((b) => b.endCoordinates[1])) - top) / (bottom - top)) * 10000,
      ),
    ]);
  }
  pageEnds.push(verses.length);
}
assert.equal(verses.length, 6214);
const surahs = existing.surahs.map((s, i) => ({ ...s, count: counts[i] }));
const source = 'https://quranapi.lissene.dev/api/v1/quran/riwayat/67a310a41b4df754ac33ca94';
await writeFile(
  new URL('../shami-data.js', import.meta.url),
  await format(
    '// Generated by scripts/build-shami-reference.mjs. Qalun / Kotteb Shami edition.\n' +
      `// Source: ${source}; extracted and structurally audited 2026-10-22.\n` +
      '// Verse-position bands support approximate workload only; these are not printed page fractions.\n' +
      `export const SHAMI_SURAHS = ${JSON.stringify(surahs)};\n` +
      `export const PAGE_ENDS = ${JSON.stringify(pageEnds)};\n` +
      `export const VERSE_TEXT = ${JSON.stringify(verses)};\n` +
      `export const VERSE_BANDS = ${JSON.stringify(bands)};\n`,
    { parser: 'babel', singleQuote: true, printWidth: 110 },
  ),
);
await writeFile(
  new URL('../surahs-qalun.json', import.meta.url),
  JSON.stringify(
    {
      reading: 'Qalun an Nafi',
      edition: 'Kotteb Shami Mushaf',
      source,
      extracted: '2026-10-22',
      printed_edition_verified: false,
      surahs,
    },
    null,
    2,
  ) + '\n',
);
console.log('Built 114 surahs, 604 pages, 6214 verses.');
